import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/services.dart';
import 'package:flutter/widgets.dart';
import 'package:shared_preferences/shared_preferences.dart';

import 'app.dart';
import 'core/firebase/firestore_cache.dart';
import 'firebase_options.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Allow portrait AND landscape on every device.
  await SystemChrome.setPreferredOrientations(DeviceOrientation.values);

  // Connect to the Firebase project (generated by `flutterfire configure`).
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // Must run before the first Firestore read or write.
  final firestore = FirebaseFirestore.instance;
  FirestoreCache.configure(firestore);

  final preferences = await SharedPreferences.getInstance();

  runApp(
    MasroufiApp(
      auth: FirebaseAuth.instance,
      firestore: firestore,
      preferences: preferences,
    ),
  );
}
